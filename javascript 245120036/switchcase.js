var grade="C"
switch(grade)
{
    case 'A':
        console.log("Excellent")
        break
    case 'B':
        console.log("very good")
        break
    case 'C':
        console.log("good")
        break
    case 'D':
        console.log("fail")
        break
    default:
        console.log("invalid grade")


}